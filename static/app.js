"use strict";
const $ = (selector) => document.querySelector(selector);
const escape = (value) =>
  String(value).replace(
    /[&<>"']/g,
    (char) =>
      ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" })[
        char
      ],
  );
let current = null,
  working = false,
  benchmarkRunning = false;
function showError(message) {
  $("#error").hidden = !message;
  $("#error").textContent = message || "";
}
function controls() {
  for (const id of ["generate", "previous", "replay", "next"])
    $("#" + id).disabled =
      working ||
      benchmarkRunning ||
      (!current && id !== "generate") ||
      (id === "previous" && current?.batch === 0) ||
      (id === "next" &&
        current &&
        (current.batch + 2) * current.size > 1000000);
  $("#run-benchmark").disabled = !current || working || benchmarkRunning;
}
async function request(path, body) {
  const response = await fetch(path, {
    method: "POST",
    headers: { "Content-Type": "application/json" },
    body: JSON.stringify(body),
  });
  let data;
  try {
    data = await response.json();
  } catch {
    throw Error(
      "The server returned an unreadable response. Please try again.",
    );
  }
  if (!response.ok) throw Error(data.error || "The request failed.");
  return data;
}
function card(person) {
  const p = person.physical,
    g = person.coordinates;
  return `<article class="contact"><div class="contact-top"><span class="contact-number">#${String(person.number).padStart(6, "0")}</span><span class="locale-badge">${escape(person.locale)}</span></div><h3 lang="${person.locale}">${escape(person.display_name)}</h3><div class="latin-name">${escape(person.latin_name)} · ${person.gender === "F" ? "Female" : "Male"}</div><dl><div class="field"><dt>Email</dt><dd>${escape(person.email)}</dd></div><div class="field"><dt>Phone</dt><dd>${escape(person.phone.formatted)}</dd></div><div class="field address"><dt>Address</dt><dd lang="${person.locale}">${escape(person.address.formatted)}</dd></div></dl><div class="attributes"><div class="attribute"><small>Height</small><strong>${escape(p.height_cm)} cm</strong></div><div class="attribute"><small>Weight</small><strong>${escape(p.weight_kg)} kg</strong></div><div class="attribute"><small>Eyes</small><strong>${escape(p.eye_color)}</strong></div><div class="attribute"><small>Blood group</small><strong>${escape(p.blood_group)}</strong></div></div><div class="coordinates">LAT ${Number(g.latitude).toFixed(6)} &nbsp; LON ${Number(g.longitude).toFixed(6)}</div></article>`;
}
async function load(params) {
  if (working || benchmarkRunning) return;
  working = true;
  controls();
  showError("");
  $("#database-status").textContent = "Generating contacts in PostgreSQL…";
  try {
    const result = await request("/api/users", {
      locale: params.locale,
      seed: params.seed,
      batch: params.batch,
      size: params.size,
    });
    current = result;
    $("#contacts").innerHTML = result.users.map(card).join("");
    $("#results-title").textContent =
      `${result.locale === "zh-CN" ? "China" : "South Korea"} · Batch ${result.batch + 1}`;
    $("#range-label").textContent =
      `RECORDS ${result.start.toLocaleString()}–${result.end.toLocaleString()}`;
    $("#result-meta").textContent =
      `${result.users.length} contacts · seed ${result.seed} · dataset ${result.version}`;
    $("#coordinate-note").hidden = false;
    $("#database-status").innerHTML = "<i></i> Generated by PostgreSQL";
    $("#database-status").classList.add("connected");
    const url = new URL(location.href);
    url.searchParams.set("locale", result.locale);
    url.searchParams.set("seed", result.seed);
    url.searchParams.set("batch", result.batch);
    url.searchParams.set("size", result.size);
    history.replaceState(null, "", url);
    $("#benchmark-result").textContent = "";
  } catch (error) {
    showError(error.message);
    $("#database-status").textContent = "Database not ready";
    $("#database-status").classList.remove("connected");
  } finally {
    working = false;
    controls();
  }
}
$("#generate-form").addEventListener("submit", (event) => {
  event.preventDefault();
  load({
    locale: $("#locale").value,
    seed: $("#seed").value,
    size: Number($("#size").value),
    batch: 0,
  });
});
$("#previous").addEventListener("click", () =>
  load({ ...current, batch: current.batch - 1 }),
);
$("#next").addEventListener("click", () =>
  load({ ...current, batch: current.batch + 1 }),
);
$("#replay").addEventListener("click", () => load(current));
$("#run-benchmark").addEventListener("click", async () => {
  if (!current || working || benchmarkRunning) return;
  benchmarkRunning = true;
  controls();
  showError("");
  $("#benchmark-result").textContent = "Running SQL benchmark. Please wait…";
  try {
    const result = await request("/api/benchmark", {
      locale: current.locale,
      seed: current.seed,
      count: Number($("#benchmark-count").value),
    });
    $("#benchmark-result").innerHTML =
      `<strong>${Number(result.users_per_second).toLocaleString("en-US", { maximumFractionDigits: 2 })}</strong> users / second<small>${result.users.toLocaleString()} contacts in ${Number(result.seconds).toFixed(3)} s · batch size ${result.batch_size} · ${escape(result.locale)} · checksum ${escape(result.checksum.slice(0, 12))}</small>`;
  } catch (error) {
    showError(error.message);
    $("#benchmark-result").textContent = "Benchmark did not complete.";
  } finally {
    benchmarkRunning = false;
    controls();
  }
});
(async () => {
  try {
    const response = await fetch("/api/catalog");
    const info = await response.json();
    if (!response.ok) throw Error(info.error || "Database unavailable");
    $("#locale").innerHTML = info.locales
      .map(
        (item) =>
          `<option value="${escape(item.code)}">${escape(item.label)}</option>`,
      )
      .join("");
  } catch (error) {
    showError(error.message);
    $("#database-status").textContent = "Database not ready";
    return;
  }
  const query = new URLSearchParams(location.search),
    locale = query.get("locale"),
    seed = query.get("seed"),
    size = query.get("size"),
    batch = query.get("batch");
  if (["zh-CN", "ko-KR"].includes(locale)) $("#locale").value = locale;
  if (seed !== null && /^\d+$/.test(seed) && Number(seed) <= 2147483647)
    $("#seed").value = seed;
  if (["10", "25", "50"].includes(size)) $("#size").value = size;
  load({
    locale: $("#locale").value,
    seed: $("#seed").value,
    size: Number($("#size").value),
    batch:
      batch !== null && /^\d+$/.test(batch) && Number(batch) <= 999999
        ? Number(batch)
        : 0,
  });
})();
